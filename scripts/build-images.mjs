// Turns the AI illustrations in assets/img/*.png|jpg|webp into small WebP files in public/img/
// and writes the list of available images to src/generated/images.js.
// Near-white backgrounds touching the corners are made transparent.
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const SRC = 'assets/img', OUT = 'public/img', LIST = 'src/generated/images.js';
fs.mkdirSync(OUT, { recursive: true });
const files = fs.existsSync(SRC) ? fs.readdirSync(SRC).filter(f => /\.(png|jpe?g|webp)$/i.test(f)) : [];
const norm = n => n.toLowerCase().replace(/\.[a-z0-9]+$/, '').replace(/\s*\(\d+\)$/, '').trim().replace(/[\s-]+/g, '_');
const keys = [];

for (const f of files) {
  const key = norm(f);
  const { data, info } = await sharp(path.join(SRC, f)).resize(360, 360, { fit: 'inside', withoutEnlargement: true })
    .ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const near = i => data[i + 3] > 200 && data[i] > 232 && data[i + 1] > 232 && data[i + 2] > 232;
  const corners = [0, w - 1, (h - 1) * w, (h - 1) * w + w - 1];
  if (corners.filter(p => near(p * 4)).length >= 3) {
    const seen = new Uint8Array(w * h), st = corners.filter(p => near(p * 4));
    while (st.length) {
      const p = st.pop(); if (seen[p]) continue; seen[p] = 1;
      const i = p * 4; if (!near(i)) continue; data[i + 3] = 0;
      const x = p % w, y = (p / w) | 0;
      if (x > 0) st.push(p - 1); if (x < w - 1) st.push(p + 1); if (y > 0) st.push(p - w); if (y < h - 1) st.push(p + w);
    }
  }
  await sharp(data, { raw: { width: w, height: h, channels: 4 } }).webp({ quality: 88 }).toFile(path.join(OUT, key + '.webp'));
  keys.push(key);
}
fs.writeFileSync(LIST, '// generated by scripts/build-images.mjs — do not edit by hand\nexport const BUNDLED_IMAGES = ' + JSON.stringify(keys.sort(), null, 0) + ';\n');
console.log(`images: ${keys.length} bundled${keys.length ? ' → ' + keys.join(', ') : ''}`);
